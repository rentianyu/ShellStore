    // ---------------- 渲染用的极简结构 ----------------

    enum class Kind { TITLE, META, SECTION, NOTICE, BULLET, PARA }

    data class Block(val kind: Kind, val text: String)

    /** "user" | "privacy" */
    fun blocks(which: String): List<Block> =
        parse(if (which == "user") USER_AGREEMENT else PRIVACY_POLICY)

    /** 首次启动页的摘要：首行不是标题 */
    fun summaryBlocks(): List<Block> = parse(CONSENT_SUMMARY, titleLine = false)

    fun parse(text: String, titleLine: Boolean = true): List<Block> {
        val out = mutableListOf<Block>()
        text.split('\n').forEachIndexed { i, raw ->
            val line = raw.trim()
            if (line.isEmpty()) return@forEachIndexed
            val kind = when {
                i == 0 && titleLine -> Kind.TITLE
                line.startsWith("生效日期") || line.startsWith("版本：") -> Kind.META
                line.startsWith("【") && line.endsWith("】") -> Kind.NOTICE
                line.startsWith("- ") -> Kind.BULLET
                // 一、二、…十二、
                line.length > 2 && line[1] == '、' && line.substringBefore('、').length <= 3 -> Kind.SECTION
                else -> Kind.PARA
            }
            out.add(Block(kind, if (kind == Kind.BULLET) line.removePrefix("- ").trim() else line))
        }
        return out
    }
